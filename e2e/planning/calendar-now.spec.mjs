import { test, expect, useApp } from '../fixtures.mjs';
import { reveal } from '../helpers/menu-controls.mjs';

const app = useApp(async store => ({ project: await store.createProject({ title: 'Calendar clock' }) }));
test('Week keeps a live local-time line aligned through zoom, midnight and navigation @gate', async ({ page }) => {
  await page.clock.install({ time: new Date('2026-11-06T23:58:00') });
  await page.goto(`${app.base}/#project/${app.project.id}/calendar`);
  await (await reveal(page.locator('#calendar-mode'))).selectOption('week');
  const now = page.locator('[data-calendar-now]');
  await expect(now).toHaveCount(1);
  await expect(now).toHaveAttribute('aria-label', 'Current time 23:58');
  await expect(now.locator('..')).toHaveAttribute('data-calendar-date', '2026-11-06');
  await expect(now).toHaveCSS('pointer-events', 'none');
  const scroll = page.locator('.calendar-hours-scroll');
  await scroll.evaluate(el => { el.scrollTop = 500; });
  const position = await scroll.evaluate(el => el.scrollTop);
  await page.clock.fastForward(60000);
  await expect(now).toContainText('23:59');
  expect(await scroll.evaluate(el => el.scrollTop)).toBe(position);
  await page.getByRole('button', { name: 'Zoom in hours', exact: true }).click();
  expect(await now.evaluate(el => parseFloat(el.style.top))).toBeCloseTo(1439 / 1440 * 100, 3);
  await page.clock.fastForward(60000);
  await expect(now.locator('..')).toHaveAttribute('data-calendar-date', '2026-11-07');
  await expect(now).toContainText('00:00');
  await page.getByRole('button', { name: 'Show weekends', exact: true }).click();
  await expect(now).toHaveCount(0);
  await page.getByRole('button', { name: 'Show weekends', exact: true }).click();
  await expect(now).toHaveCount(1);
  await page.getByRole('button', { name: 'Next period', exact: true }).click();
  await expect(now).toHaveCount(0);
  await page.getByRole('button', { name: 'Previous period', exact: true }).click();
  await expect(now).toHaveCount(1);
  await page.clock.setSystemTime(new Date('2026-11-07T08:42:00'));
  await page.evaluate(() => document.dispatchEvent(new Event('visibilitychange')));
  await expect(now).toContainText('08:42');
  await (await reveal(page.locator('#calendar-mode'))).selectOption('month');
  await page.clock.fastForward(60000);
  await expect(now).toHaveCount(0);
  await (await reveal(page.locator('#calendar-mode'))).selectOption('week');
  await expect(now).toHaveCount(1);
  await expect(now).toContainText('08:43');
});
