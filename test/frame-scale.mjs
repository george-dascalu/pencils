import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { chromium } from 'playwright';
import { Store } from '../server/store.js';
import { createServer } from '../server/index.js';
import { BOARD_LIMITS } from '../public/board-limits.js';
const root=await fs.mkdtemp(path.join(os.tmpdir(),'pencils-frame-scale-'));
const store=new Store(root);await store.init();
const project=await store.createProject({title:'Frame duplication'});
let board=(await store.snapshot(project.id)).boards[0];
const count=5000, nodes=[];
for(let i=0;i<count;i++) {
  const x=i%100*1000,y=Math.floor(i/100)*1000;
  nodes.push({id:`frame-${i}`,type:'frame',text:`Frame ${i}`,x,y,w:800,h:600});
  nodes.push({id:`child-${i}`,type:'sticky',text:`Child ${i}`,x:x+50,y:y+100,w:200,h:160,frame:`frame-${i}`});
}
board=await store.updateBoard(project.id,board.id,{revision:board.revision,nodes,edges:[]});
const server=createServer(store,{productionAssets:process.env.PRODUCTION_ASSETS==='1'});
await new Promise(r=>server.listen(0,'127.0.0.1',r));
const base=`http://127.0.0.1:${server.address().port}`,browser=await chromium.launch();
const page=await browser.newPage({viewport:{width:1500,height:1000}});page.setDefaultTimeout(60000);
const errors=[];page.on('pageerror',e=>errors.push(e.message));
const current=async()=>(await store.snapshot(project.id)).boards[0];
try {
  console.log('Fixture ready: 5,000 frames and 5,000 children');
  await page.goto(`${base}/#project/${project.id}/board/${board.id}`);
  await page.waitForFunction(()=>document.querySelector('.board-capacity')?.dataset.frameCount==='5000');
  await page.waitForTimeout(1600);
  console.log('Board loaded');
  await page.locator('#canvas').focus();
  await page.keyboard.press('Control+a');await page.keyboard.press('Control+c');
  console.log('Selected and copied');
  const start=performance.now();
  await page.keyboard.press('Control+v');
  await page.waitForFunction(()=>document.querySelector('.board-capacity')?.dataset.frameCount==='10000');
  console.log('Paste rendered');
  let saved;
  for(let i=0;i<200;i++) {saved=await current();if(saved.nodes.length===20000)break;await page.waitForTimeout(100);}
  assert.equal(saved.nodes.length,20000);
  const ids=new Set(saved.nodes.map(n=>n.id));
  assert.equal(ids.size,20000);
  assert.equal(saved.nodes.filter(n=>n.type==='frame').length,10000);
  assert.ok(saved.nodes.filter(n=>n.type!=='frame').every(n=>ids.has(n.frame)));
  assert.ok(saved.nodes.filter(n=>n.id.startsWith('child-')).every(n=>n.frame===n.id.replace('child-','frame-')),'Pasting frames preserves the original frames’ children');
  console.log(`PASS: copy/paste 5,000 frames + children to 10,000 frames saved in ${Math.round(performance.now()-start)} ms`);
  await page.keyboard.press('Escape');
  await page.reload();
  await page.waitForFunction(()=>document.querySelector('.board-capacity')?.dataset.frameCount==='10000');
  await page.waitForTimeout(1600);
  await page.evaluate(()=>document.querySelector('[data-pro=outline]').click());
  assert.equal(await page.locator('[data-frame-row]').count(),50);
  await page.getByRole('button',{name:'Next frames',exact:true}).click();
  await page.locator('[data-frame-row="frame-50"]').waitFor();
  await page.getByRole('button',{name:'Previous frames',exact:true}).click();
  await page.locator('[data-frame-row="frame-0"]').waitFor();
  await page.screenshot({path:'/tmp/pencils-frame-scale-desktop.png'});
  await page.getByRole('button',{name:'Collapse sidebar',exact:true}).click();
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'/tmp/pencils-frame-scale-mobile.png'});
  await page.setViewportSize({width:1500,height:1000});
  const presentation=saved.nodes.filter(n=>n.type==='frame').map(n=>n.id);
  saved=await store.updateBoard(project.id,board.id,{revision:(await current()).revision,presentation});
  assert.equal(saved.presentation.length,10000);
  assert.equal((await store.read(store.file(project.id,'boards',board.id))).data.nodes.length,20000);
  assert.ok(BOARD_LIMITS.frames>=10000);
  assert.deepEqual(errors,[]);
  console.log('PASS: reload, native vault persistence, paged frame navigation and 10,000 presentation frames');
} finally {await browser.close();server.closeAllConnections();await new Promise(r=>server.close(r));await store.close();await fs.rm(root,{recursive:true,force:true});}
