import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { chromium } from 'playwright';
import AxeBuilder from '@axe-core/playwright';
import { Store } from '../server/store.js';
import { createServer } from '../server/index.js';
import { APP_VERSION } from '../public/app-version.js';
const root = await fs.mkdtemp(path.join(os.tmpdir(), 'pencils-task-cards-'));
const store = new Store(root); await store.init();
const project = await store.createProject({ title: 'Task details' });
const original = await store.createTask(project.id, { title: 'Collect inspiration and early ideas for a calmer workspace', assignee: 'Alex', priority: 'low', status: 'todo', body: 'First draft\n\nKeep this paragraph.' });
const task = await store.updateTask(project.id, original.id, { revision: original.revision, assignee: 'George', priority: 'high', status: 'in-progress', body: 'Final draft\n\nKeep this paragraph.', comments: [{ id: 'legacy', text: '**A literal old comment**', author: 'Alex', created: '2026-10-20T12:00:00Z' }] });
const b = (await store.snapshot(project.id)).boards[0];
await store.updateBoard(project.id, b.id, { revision: b.revision, nodes: [{ id: 'card', type: 'task', task: task.id, x: 150, y: 120, w: 340, h: 150, taskCollapsed: true }], edges: [] });
const server = createServer(store, { productionAssets: process.env.PRODUCTION_ASSETS === '1' });
await new Promise(r => server.listen(0, '127.0.0.1', r));
const base = `http://127.0.0.1:${server.address().port}`;
const browser = await chromium.launch();
const context = await browser.newContext({ viewport: { width: 1500, height: 1000 } });
const page = await context.newPage(), errors = [];
page.on('pageerror', e => errors.push(e.message));
const until = async f => { for (let i=0;i<150;i++) { if(await f())return; await page.waitForTimeout(50); } throw Error('Timed out'); };
const saved = async () => (await store.snapshot(project.id)).tasks.find(t => t.id === task.id);
try {
  assert.equal((await (await fetch(base + '/api/health')).json()).version, APP_VERSION);
  await page.goto(`${base}/#project/${project.id}/board/${b.id}`);
  const card = page.locator('[data-node=card]'); await card.locator('.live-card-state').waitFor();
  assert.deepEqual(await card.locator('.live-card-state').evaluate(el => [...el.children].map(c=>c.className)), ['canvas-task-assignee','canvas-task-priority priority high','canvas-task-status','button small canvas-task-due']);
  assert.equal(await card.locator('.canvas-task-assignee .task-assignee').textContent(), 'G');
  const title = await card.locator('.task-title').evaluate(el => ({ wrap:getComputedStyle(el).whiteSpace, size:getComputedStyle(el).fontSize, tooltip:el.title }));
  assert.equal(title.wrap,'nowrap'); assert.equal(title.size,'14px'); assert.equal(title.tooltip,task.title);
  assert.match(await page.locator('#save-state').textContent(), new RegExp(`v${APP_VERSION}`));
  assert.doesNotMatch(await page.locator('#save-state').textContent(), /Connected to local server/);
  await page.route('**/api/health', route => route.fulfill({ json: { ok:true, version:'99.0.0' } }));
  await page.evaluate(() => dispatchEvent(new Event('focus')));
  await page.locator('.app-update-available').waitFor();
  assert.match(await page.locator('#save-state').textContent(), /Update available/);
  const nav=await page.locator('.board-project-tools').boundingBox(), statusBounds=await page.locator('.top-actions').boundingBox();
  assert.ok(nav.x+nav.width <= statusBounds.x, 'The update indicator does not overlap project navigation');
  await card.locator('[data-pro=comments]').click();
  const panel=page.locator('.board-comments'), rich=panel.getByRole('textbox',{name:'Comment',exact:true});
  assert.equal(await panel.locator('[data-comment-id=legacy] .comment-body strong').count(), 0);
  await rich.fill('Formatted comment'); await rich.press('Control+a');
  await panel.getByRole('button',{name:'Bold',exact:true}).click();
  assert.equal(await rich.locator('b,strong').textContent(),'Formatted comment');
  await rich.press('Control+Enter');
  await until(async()=>(await saved()).comments.length===2);
  const added=(await saved()).comments.at(-1);
  assert.equal(added.format,'markdown'); assert.equal(added.text,'**Formatted comment**');
  const comment=panel.locator(`[data-comment-id="${added.id}"]`);
  assert.equal(await comment.locator('.comment-body strong').textContent(),'Formatted comment');
  assert.deepEqual(await comment.locator('.comment-actions').evaluate(el=>[...el.children].map(n=>n.matches('details')?'emoji':n.hasAttribute('data-comment-reply')?'reply':'delete')),['reply','emoji','delete']);
  const color=await comment.locator('[data-comment-delete]').evaluate(el=>getComputedStyle(el).color);
  assert.equal(color,'rgb(179, 68, 56)');
  await comment.getByLabel('Add reaction',{exact:true}).click();
  assert.ok(await comment.locator('.comment-emoji-picker').isVisible());
  await comment.locator('.comment-emoji-picker [data-emoji="🎉"]').click();
  await until(async()=>(await saved()).comments.at(-1).reactions?.length===1);
  await panel.getByRole('button',{name:'Markdown',exact:true}).click();
  await panel.getByRole('textbox',{name:'Comment Markdown',exact:true}).fill('## Update\n\n- First point\n- **Second** point\n\n[Reference](https://example.com)\n\n<script>window.commentAttack=1</script>');
  await panel.getByRole('button',{name:'Rich text',exact:true}).click();
  assert.equal(await rich.locator('li').count(),2); assert.equal(await rich.locator('h2').textContent(),'Update');
  await rich.press('Control+Enter'); await until(async()=>(await saved()).comments.length===3);
  assert.equal(await panel.locator('.comment-body li').count(),2);
  assert.equal(await page.evaluate(()=>window.commentAttack),undefined);
  assert.equal(await panel.locator('.comment-body script').count(),0);
  await fs.mkdir('artifacts',{recursive:true});
  await page.screenshot({path:'artifacts/task-card-rich-comments.png'});
  const results=await new AxeBuilder({page}).include('.board-comments').withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
  assert.deepEqual(results.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)})),[]);
  await panel.getByRole('button',{name:'Close comments',exact:true}).click();
  await card.locator('[data-pro=task-details]').click();
  const geometry=await page.locator('#task-form').evaluate(form=>{
    const rect=selector=>form.querySelector(selector).getBoundingClientRect().toJSON();
    return { head:rect('.task-editor-header-row'), title:rect('[name=title]'), fields:[...form.querySelectorAll('.task-metadata-main > .field')].map(el=>el.getBoundingClientRect().y), tools:[...form.querySelectorAll('.task-description .task-rich-tools > .selection-group,.task-description .rich-toolbar')].filter(el=>el.getClientRects().length).map(el=>el.getBoundingClientRect().y) };
  });
  assert.ok(geometry.title.y >= geometry.head.y + geometry.head.height);
  assert.ok(Math.max(...geometry.fields)-Math.min(...geometry.fields)<2);
  assert.ok(Math.max(...geometry.tools)-Math.min(...geometry.tools)<5);
  await page.getByRole('button',{name:'Version history',exact:true}).click();
  const history=page.getByLabel('Task version history',{exact:true});
  await history.locator('.task-history-version').first().waitFor();
  await history.locator('details').evaluateAll(items=>items.forEach(el=>el.open=true));
  assert.match(await history.textContent(),/Before/); assert.match(await history.textContent(),/After/);
  assert.ok(await history.locator('.task-history-before').filter({hasText:'Alex'}).count());
  assert.ok(await history.locator('.task-history-after').filter({hasText:'George'}).count());
  assert.ok(await history.locator('.task-history-before').filter({hasText:'Low'}).count());
  assert.ok(await history.locator('.task-history-after').filter({hasText:'High'}).count());
  assert.equal(await history.locator('pre:empty').count(),0);
  await page.screenshot({path:'artifacts/task-history-changes.png'});
  const audit=await new AxeBuilder({page}).include('.task-history-panel').withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
  assert.deepEqual(audit.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)})),[]);
  await page.getByRole('button',{name:'Close version history',exact:true}).click();
  await page.getByRole('button',{name:'Task comments',exact:true}).click();
  const embedded=page.locator('.task-comments-panel');
  await embedded.getByRole('textbox',{name:'Comment',exact:true}).fill('Reply from the task editor');
  await embedded.getByRole('button',{name:'Add comment',exact:true}).click();
  await until(async()=>(await saved()).comments.length===4);
  assert.equal((await saved()).body,task.body);
  await page.setViewportSize({width:390,height:844});
  await page.locator('[data-editor-pane=details]').click();

  assert.ok(await page.locator('#task-form').evaluate(el=>el.scrollWidth<=el.clientWidth));
  await page.screenshot({path:'artifacts/task-modal-mobile.png'});
  await page.locator('[data-editor-pane=comments]').click();
  await embedded.getByRole('textbox',{name:'Comment',exact:true}).fill('Mobile draft');
  for (const theme of ['light','dark']) {
    await page.evaluate(theme=>window.PencilsAppearance.write({theme}),theme);
    assert.ok(await page.locator('.task-comments-panel').evaluate(el=>el.scrollWidth<=el.clientWidth));
    const check=await new AxeBuilder({page}).include('.task-comments-panel').withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
    assert.deepEqual(check.violations.map(v=>({id:v.id,nodes:v.nodes.map(n=>n.target)})),[]);
  }
  await page.screenshot({path:'artifacts/task-comments-mobile.png'});
  assert.deepEqual(errors,[]);
  console.log('PASS: compact task layout, rich comments and safe rendering, emoji actions, shared task conversation, before/after history, accessibility, current version and stale-browser indicator');
} catch(error) { await page.screenshot({path:'artifacts/task-card-comments-history-failure.png'}); throw error; }
finally { await browser.close(); server.closeAllConnections(); await new Promise(r=>server.close(r)); await store.close(); await fs.rm(root,{recursive:true,force:true}); }
