import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { chromium, firefox } from 'playwright';
import AxeBuilder from '@axe-core/playwright';
import { Store } from '../server/store.js';
import { createServer } from '../server/index.js';
const root = await fs.mkdtemp(path.join(os.tmpdir(), 'pencils-document-controls-'));
const store = new Store(root); await store.init();
const project = await store.createProject({ title: 'Document controls' });
const body = '# Notebook\n\n- [ ] Switch to **Source** and find `inline code` with *emphasis*.\n\nAnother **bold** word.\n\n| One | Two |\n| --- | --- |\n| Alpha | Beta |\n';
const doc = await store.createDocument(project.id, { title: 'Notebook', body });
const server = createServer(store, { productionAssets: process.env.PRODUCTION_ASSETS === '1' });
await new Promise(r => server.listen(0,'127.0.0.1',r));
const browser = await (process.env.BROWSER === 'firefox' ? firefox : chromium).launch();
const context = await browser.newContext({ viewport: { width: 1500, height: 1000 } });
const page = await context.newPage();
const errors = []; page.on('pageerror', e => errors.push(e.message));
const click = name => page.getByRole('button', { name, exact: true }).click();
try {
  await page.goto(`http://127.0.0.1:${server.address().port}/#project/${project.id}/documents/${doc.id}`);
  await page.locator('.cm-content').waitFor();
  const positioning = await page.evaluate(() => {
    const box = s => document.querySelector(s).getBoundingClientRect().toJSON();
    return { format: box('.document-formatting'), views: box('.document-view-controls'), footer: box('.document-save'), versions: box('.document-heading [data-document-action=versions]'), tools: box('.document-heading [data-document-action=tools]') };
  });
  assert.ok(positioning.format.x < positioning.views.x);
  assert.ok(positioning.versions.x < positioning.tools.x);
  assert.ok(positioning.footer.height <= 24 && positioning.footer.width < 250);
  assert.equal(await page.locator('.document-modes [data-document-mode]').count(), 3);
  assert.doesNotMatch(await page.locator('.document-save').textContent(), /Saved|Version/);
  assert.equal(await page.locator('.document-heading [data-document-action=versions] svg').count(), 1);
  // Use CodeMirror's actual selection and coordinates to test token-level reveal.
  await page.evaluate(async () => {
    const { EditorView } = await import('/vendor/editor/deps.js');
    const view = EditorView.findFromDOM(document.querySelector('.cm-editor'));
    view.focus(); view.dispatch({ selection: { anchor: view.state.doc.toString().indexOf('Source') + 2 } });
  });
  const line = page.locator('.cm-line').filter({ hasText: 'Switch to' });
  assert.match(await line.textContent(), /\*\*Source\*\*/);
  assert.doesNotMatch(await line.textContent(), /\[ \]|`inline code`|\*emphasis\*/);
  assert.equal(await line.locator('input[type=checkbox]').count(), 1);
  const point = await page.evaluate(async () => {
    const { EditorView } = await import('/vendor/editor/deps.js');
    const view = EditorView.findFromDOM(document.querySelector('.cm-editor'));
    const p = view.coordsAtPos(view.state.doc.toString().indexOf('emphasis') + 3);
    return { x: p.left + 1, y: (p.top + p.bottom) / 2 };
  });
  await page.mouse.move(point.x, point.y); await page.waitForTimeout(150);
  assert.match(await line.textContent(), /\*emphasis\*/);
  assert.doesNotMatch(await line.textContent(), /\[ \]|`inline code`/);
  await page.mouse.move(1,1);
  await click('Insert');
  for (const label of ['Structure','Formatting','Components','References & files']) assert.equal(await page.getByRole('region', { name: label, exact: true }).count(), 1);
  assert.equal(await page.locator('.document-insert-options button:not(:has(svg))').count(), 0);
  await fs.mkdir('artifacts', { recursive: true });
  await page.screenshot({ path: 'artifacts/document-insert-categories.png' });
  await page.keyboard.press('Escape');
  await click('Find in document');
  const find = page.locator('.cm-search input[name=search]');
  await find.fill('Source'); await find.press('Enter');
  const bar = await page.locator('.cm-panels').boundingBox(), close = await page.locator('.cm-search button[name=close]').boundingBox();
  console.log("Search geometry", { bar, close });
  await page.screenshot({ path: "artifacts/document-search-check.png" });
  assert.ok(bar.width <= 502 && bar.height < 50); assert.ok(close.width >= 30 && close.height >= 30);
  assert.ok(bar.x > 800, `Search should stay on the right, got ${bar.x}`);
  await page.getByRole('button', { name: 'Show replace', exact: true }).focus();
  await page.keyboard.press('Enter'); await page.getByRole('textbox', { name: 'Replace with', exact: true }).fill('Live preview');
  await click('Replace next');
  await page.waitForFunction(() => document.querySelector('textarea[name=body]').value.includes('**Live preview**'));
  await page.getByLabel('Search options', { exact: true }).click();
  await click('Regular expression'); await find.fill('[');
  assert.equal(await find.getAttribute('aria-invalid'), 'true');
  assert.match(await page.locator('.cm-search [role=status]').textContent(), /Invalid/);
  await click('Regular expression'); await find.fill('preview');
  await page.getByLabel('Search options', { exact: true }).click();
  await click('Hide replace');
  for (const theme of ['light','dark']) {
    await page.evaluate(theme => window.PencilsAppearance.write({ theme }), theme);
    await click('Find in document'); await find.fill('preview');
    const result = await new AxeBuilder({ page }).include('.document-controls').include('.document-heading').include('.cm-search').withTags(['wcag2a','wcag2aa','wcag21aa']).analyze();
    assert.deepEqual(result.violations.map(v => ({ id: v.id, targets: v.nodes.map(n => n.target) })), []);
  }
  await page.evaluate(() => window.PencilsAppearance.write({ theme: 'light' }));
  await click('Find in document'); await find.fill('preview');
  await page.screenshot({ path: 'artifacts/document-controls-desktop.png' });
  await click('Close search'); await click('Page versions');
  await page.getByRole('dialog', { name: 'Page versions', exact: true }).waitFor();
  await page.keyboard.press('Escape');
  await click('Reading'); await click('Find in document');
  assert.equal(await page.getByRole('button', { name: 'Reading', exact: true }).getAttribute('aria-pressed'), 'true');
  const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 }, hasTouch: true, isMobile: process.env.BROWSER !== 'firefox' });
  const mobile = await mobileContext.newPage();
  mobile.on('pageerror', e => errors.push(e.message));
  await mobile.goto(`http://127.0.0.1:${server.address().port}/#project/${project.id}/documents/${doc.id}`);
  await mobile.locator('.cm-content').waitFor();
  await mobile.getByRole('button', { name: 'Find in document', exact: true }).tap();
  await mobile.locator('.cm-search input[name=search]').fill('preview');
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.ok((await mobile.getByRole('button', { name: 'Close search', exact: true }).boundingBox()).height >= 44);
  assert.ok(await mobile.locator('.cm-panels').evaluate(el => el.scrollWidth <= el.clientWidth));
  await mobile.screenshot({ path: 'artifacts/document-controls-mobile.png' });
  await mobile.getByRole('button', { name: 'Reading', exact: true }).tap();
  await mobile.getByRole('button', { name: 'Find in document', exact: true }).tap();
  await mobile.getByRole('searchbox', { name: 'Find in document', exact: true }).fill('preview');
  assert.ok(await mobile.evaluate(() => document.documentElement.scrollWidth <= innerWidth));
  assert.equal(await mobile.getByRole('button', { name: 'Reading', exact: true }).getAttribute('aria-pressed'), 'true');
  await mobileContext.close();
  assert.deepEqual(errors, []);
  console.log('PASS: focused/hovered word reveal, grouped toolbar, categorized Insert icons, compact search/replace, versions icon, corner counts, mobile and themed accessibility');
} finally { await browser.close(); server.closeAllConnections(); await new Promise(r=>server.close(r)); await store.close(); await fs.rm(root,{recursive:true,force:true}); }
