import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs/promises';
import os from 'node:os';
import path from 'node:path';
import { Store } from '../server/store.js';
import { moveTree } from '../server/folder-tree-moves.js';
for (const kind of ['document', 'board']) test(`${kind} tree moves preserve content, save order and reject stale or invalid moves atomically`, async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), 'pencils-tree-move-'));
  const store = new Store(root); await store.init();
  t.after(async () => { await store.close(); await fs.rm(root, { recursive: true, force: true }); });
  let project = await store.createProject({ title: 'Organise' });
  project = await store.updateProject(project.id, { revision: project.revision, [`${kind}_folders`]: [{ id: 'a', title: 'Archive', parent: null }, { id: 'b', title: 'Notes', parent: null }] });
  const create = value => kind === 'document' ? store.createDocument(project.id, value) : store.createBoard(project.id, value);
  const get = id => kind === 'document' ? store.getDocument(project.id, id) : store.read(store.file(project.id, 'boards', id)).then(r => store.public(r, store.file(project.id, 'boards', id)));
  const item = await create({ title: 'Keep content', body: '# Markdown' });
  const run = (move, revision = project.revision, itemRevision = item.revision) => store.mutate(() => moveTree(store, project.id, { revision, item_revision: itemRevision, tree_move: { kind, ...move } }));
  let result = await run({ what: 'item', id: item.id, parent: 'a', before: null });
  project = result.project;
  assert.equal(result.item.folder, 'a');
  assert.equal((await get(item.id)).title, item.title);
  if (kind === 'document') assert.equal((await get(item.id)).body, '# Markdown');
  await assert.rejects(() => run({ what: 'item', id: item.id, parent: 'b', before: null }), e => e.status === 409);
  const before = await get(item.id);
  result = await run({ what: 'item', id: item.id, parent: 'a', before: 'item:' + item.id }, project.revision, before.revision);
  assert.equal(result.item, null);
  assert.equal(result.project.revision, project.revision, 'a no-op writes nothing');
  result = await run({ what: 'folder', id: 'b', parent: null, before: 'folder:a' }); project = result.project;
  assert.deepEqual(project[`${kind}_order`].slice(0, 2), ['folder:b', 'folder:a']);
  assert.equal((await get(item.id)).revision, before.revision, 'reordering never versions the content');
  for (const move of [{ what: 'folder', id: 'a', parent: 'a' }, { what: 'item', id: item.id, parent: 'missing' }, { what: 'item', id: item.id, parent: 'b', before: 'item:unknown' }]) {
    await assert.rejects(() => run(move, project.revision, before.revision), e => e.status === 400);
    assert.equal((await get(item.id)).folder, 'a');
    assert.equal((await store.read(store.file(project.id, 'project'))).revision, project.revision);
  }
  await assert.rejects(() => run({ what: 'folder', id: 'a', parent: null }, 'stale'), e => e.status === 409);
  result = await run({ what: 'item', id: item.id, parent: null, before: null }, project.revision, before.revision);
  project = result.project;
  assert.equal((await get(item.id)).folder, null);
  const restored = await get(item.id), savedWrite = store.write.bind(store);
  store.write = async (file, ...args) => {
    if (file === store.file(project.id, 'project')) throw Error('simulated project write failure');
    return savedWrite(file, ...args);
  };
  await assert.rejects(() => run({what:'item',id:item.id,parent:'b',before:null}, project.revision, restored.revision), /simulated/);
  store.write = savedWrite;
  assert.equal((await get(item.id)).revision, restored.revision, 'the journal rolls the file move back if its order cannot save');
  assert.equal((await get(item.id)).folder, null);
  for (const tree_move of [null, {kind:'other'}]) await assert.rejects(() => store.mutate(() => moveTree(store, project.id, {revision:project.revision,tree_move})), e => e.status === 400 && /Choose Documents or Boards/.test(e.message));
  const broken = kind === 'document' ? 'broken.md' : 'broken.canvas';
  await fs.writeFile(path.join(root, 'Projects', project.id, kind + 's', broken), '---\ninvalid: [');
  store.changed();
  await assert.rejects(() => run({what:'folder',id:'a',parent:'b',before:null}), e => e.status === 409 && /Repair unreadable/.test(e.message));
  await fs.unlink(path.join(root, 'Projects', project.id, kind + 's', broken)); store.changed();
  const restarted = new Store(root); t.after(() => restarted.close());
  const snapshot = await restarted.snapshot(project.id);
  assert.deepEqual(snapshot.project[`${kind}_order`], project[`${kind}_order`]);
  assert.equal(snapshot[`${kind}s`].find(d => d.id === item.id).folder, null);
});
