const owner = { username: "George", admin: true };
const input = (extra = {}) => ({ id: `fr-${randomUUID()}`, title: "Improve document navigation", body: "Keep the current document visible.", priority: "normal", attachments: [{ name: "notes.md", data: Buffer.from("Supporting notes").toString("base64") }], ...extra });
async function fixture(t) {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "pencils-requests-"));
  const store = new Store(root); await store.init();
  t.after(async () => { store.close(); await store.queue; await fs.rm(root, { recursive: true, force: true }); });
  return { store, root, requests: new FeatureRequests(store) };
}
test("requests, attachments, index and updates persist; retries and stale edits are safe", async t => {
  const { store, root, requests } = await fixture(t), payload = input();
  const [a, retry] = await Promise.all([requests.create(payload, owner), requests.create(payload, owner)]);
  assert.equal(a.id, retry.id); assert.equal((await requests.list()).requests.length, 1);
  assert.match(await fs.readFile(path.join(root, "feature-requests/index.md"), "utf8"), /Improve document navigation/);
  assert.equal((await requests.attachment(a.id, a.attachments[0].id)).bytes.toString(), "Supporting notes");
  const updated = await requests.update(a.id, { revision: a.revision, status: "needs-input", note: "Please keep the search field accessible." }, owner);
  await assert.rejects(requests.update(a.id, { revision: a.revision, status: "done" }, owner), e => e.status === 409);
  const restarted = new FeatureRequests(store);
  const records = await restarted.list();
  assert.equal(records.requests[0].status, "needs-input");
  assert.equal(records.requests[0].activity.at(-1).text, updated.activity.at(-1).text);
  assert.match(await fs.readFile(path.join(root, "feature-requests/index.md"), "utf8"), /Needs input/);
  assert.equal(records.worker.state, "offline");
});
test("invalid or oversized attachments never create partial requests; symlinks are refused", async t => {
  const { root, requests } = await fixture(t);
  await assert.rejects(requests.create(input({ attachments: [{ name: "script.html", data: "YQ==" }] }), owner), e => e.status === 400);
  await assert.rejects(requests.create(input({ attachments: Array(6).fill({ name: "note.txt", data: "YQ==" }) }), owner), e => e.status === 400);
  await assert.rejects(requests.create(input({ attachments: [{ name: "large.txt", data: Buffer.alloc(10000001).toString("base64") }] }), owner), e => e.status === 400);
  assert.equal((await requests.list()).requests.length, 0);
  await assert.rejects(requests.read("../../outside"), e => e.status === 400);
  const record = await requests.create(input(), owner);
  const file = path.join(root, record.folder, "attachments", record.attachments[0].id);
  await fs.rm(file); await fs.symlink("/etc/passwd", file);
  await assert.rejects(requests.attachment(record.id, record.attachments[0].id), e => e.status === 400);
});
test("worker claims are exclusive, honour priority/pause, and preserve interrupted work", async t => {
  const { requests } = await fixture(t);
  const low = await requests.create(input({ priority: "low" }), owner);
  const high = await requests.create(input({ priority: "high" }), owner);
  await requests.configure(false);
  assert.equal((await requests.work({ action: "claim", worker: "one" })).request, null);
  await requests.configure(true);
  const claim = await requests.work({ action: "claim", worker: "one" });
  assert.equal(claim.request.id, high.id);
  assert.equal((await requests.work({ action: "claim", worker: "two" })).request, null);
  const before = await requests.read(high.id);
  await requests.work({ action: "heartbeat", worker: "one", id: high.id, lease: claim.lease });
  assert.equal((await requests.read(high.id)).revision, before.revision, "Heartbeats do not conflict with owner notes");
  await requests.update(high.id, { revision: before.revision, note: "Also check iPad" }, owner);
  assert.equal((await requests.read(high.id)).lease.token, claim.lease);
  const latest = await requests.work({ action: "heartbeat", worker: "one", id: high.id, lease: claim.lease });
  assert.notEqual(latest.ownerRevision, claim.ownerRevision, "Owner updates are detected before a prepared release");
  await assert.rejects(requests.work({ action: "complete", id: high.id, worker: "two", lease: claim.lease, status: "done", note: "Wrong worker" }), e => e.status === 409);
  await requests.work({ action: "complete", id: high.id, worker: "one", lease: claim.lease, status: "done", note: "Released and checked." });
  const second = await requests.work({ action: "claim", worker: "two" });
  assert.equal(second.request.id, low.id);
  const stale = await requests.read(low.id); stale.lease.expires = 0;
  await requests.atomic(requests.location(low.id), requests.encode(stale));
  await requests.work({ action: "claim", worker: "three" });
  assert.equal((await requests.read(low.id)).status, "needs-input");
  assert.ok(!(await requests.list()).requests.some(r => r.lease));
});
test("request routes require an administrator and worker token does not grant workspace access", async t => {
  const { store, root } = await fixture(t), auth = new Auth(store, "required");
  await auth.save({ username: "admin", password: "test-request-password", admin: true, organisations: {} });
  await auth.save({ username: "reader", password: "test-reader-password", admin: false, organisations: {} });
  const server = createServer(store, { auth }); await new Promise(r => server.listen(0, "127.0.0.1", r));
  t.after(() => new Promise(r => server.close(r)));
  const base = `http://127.0.0.1:${server.address().port}`;
  const session = await auth.login({ username: "admin", password: "test-request-password" }, "local");
  const cookie = `pencils_session=${session.token}`;
  assert.equal((await fetch(`${base}/api/feature-requests`)).status, 401);
  assert.equal((await fetch(`${base}/api/feature-requests`, { headers: { cookie } })).status, 200);
  const reader = await auth.login({ username: "reader", password: "test-reader-password" }, "local");
  assert.equal((await fetch(`${base}/api/feature-requests`, { headers: { cookie: `pencils_session=${reader.token}` } })).status, 403);
  const key = await fs.readFile(path.join(root, ".pencils/feature-worker-key"), "utf8");
  const send = (token, body) => fetch(`${base}/api/feature-request-worker`, { method: "POST", headers: { "Content-Type": "application/json", "X-Pencils-Worker": token }, body: JSON.stringify(body) });
  assert.equal((await send("bad", { action: "claim", worker: "test" })).status, 403);
  assert.equal((await send(key, { action: "heartbeat", worker: "test", state: "idle", message: "Ready" })).status, 200);
  assert.equal((await fetch(`${base}/api/projects`, { headers: { "X-Pencils-Worker": key } })).status, 401);
  assert.equal((await fetch(`${base}/api/feature-requests`, { method: "POST", headers: { cookie, "Content-Type": "application/json", Origin: "https://elsewhere.invalid" }, body: JSON.stringify(input()) })).status, 403);
});
test("worker promotion refuses concurrent edits and applies only isolated repository changes", async t => {
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "pencils-request-promotion-"));
  t.after(() => fs.rm(root, { recursive: true, force: true }));
  const live = path.join(root, "live"), stage = path.join(root, "stage");
  for (const dir of [live, stage]) {
    await fs.mkdir(dir); await command("git", ["init", "-q"], { cwd: dir });
    await fs.writeFile(path.join(dir, "app.js"), "original");
    await fs.writeFile(path.join(dir, ".gitignore"), "private/\n");
    await command("git", ["add", "-A"], { cwd: dir });
  }
  const baseline = await snapshot(live);
  await fs.writeFile(path.join(stage, "app.js"), "request change");
  await fs.writeFile(path.join(live, "app.js"), "concurrent edit");
  await assert.rejects(promote(stage, live, baseline), /no files were overwritten/);
  assert.equal(await fs.readFile(path.join(live, "app.js"), "utf8"), "concurrent edit");
  await fs.writeFile(path.join(live, "app.js"), "original");
  await fs.writeFile(path.join(stage, "added.js"), "new");
  assert.deepEqual(await promote(stage, live, baseline), ["app.js", "added.js"]);
  assert.equal(await fs.readFile(path.join(live, "app.js"), "utf8"), "request change");
});

test("worker pipeline checks isolated changes, promotes them, and records verified release", async t => {
  const { root: vault, requests } = await fixture(t);
  const root = await fs.mkdtemp(path.join(os.tmpdir(), "pencils-worker-pipeline-"));
  const oldBin = process.env.PENCILS_CODEX_BIN;
  t.after(async () => { if (oldBin === undefined) delete process.env.PENCILS_CODEX_BIN; else process.env.PENCILS_CODEX_BIN = oldBin; await fs.rm(root, { recursive: true, force: true }); });
  const pkg = { name: "worker-fixture", version: "1.0.0", type: "module", scripts: { check: "node --check app.js", test: "node app.js", build: "node --check app.js" } };
  await fs.writeFile(path.join(root, "package.json"), JSON.stringify(pkg));
  await fs.writeFile(path.join(root, "package-lock.json"), JSON.stringify({ name: pkg.name, version: pkg.version, lockfileVersion: 3, packages: { "": { name: pkg.name, version: pkg.version } } }));
  await fs.writeFile(path.join(root, "app.js"), "console.log('original');\n");
  await fs.writeFile(path.join(root, ".gitignore"), ".request-work/\n.request-input/\nnode_modules/\n");
  const cli = path.join(root, "fixture-codex.mjs");
  await fs.writeFile(cli, `#!/usr/bin/env node\nimport fs from 'node:fs';\nconst pkg=JSON.parse(fs.readFileSync('package.json'));pkg.version='1.0.1';fs.writeFileSync('package.json',JSON.stringify(pkg));fs.writeFileSync('app.js',"console.log('updated');\\n");fs.writeFileSync(process.argv[process.argv.indexOf('--output-last-message')+1],JSON.stringify({status:'ready',summary:'Updated the fixture.',validation:'Fixture syntax and execution checked.'}));\n`, { mode: 0o700 });
  process.env.PENCILS_CODEX_BIN = cli;
  await command("git", ["init", "-q"], { cwd: root });
  const request = await requests.create(input(), owner);
  const job = await requests.work({ action: "claim", worker: "fixture" });
  let released = false;
  await executeRequest(job, body => requests.work(body), { root, vault, url: "http://127.0.0.1", worker: "fixture", release: async (folder, version) => {
    assert.equal(folder, root); assert.equal(version, "1.0.1");
    assert.match(await fs.readFile(path.join(root, "app.js"), "utf8"), /updated/);
    released = true; return "fixture:rollback";
  } });
  assert.equal(released, true);
  assert.equal((await requests.read(request.id)).status, "done");
  assert.match((await requests.read(request.id)).activity.at(-1).text, /Released in v1.0.1/);
  assert.ok((await fs.readdir(path.join(vault, request.folder))).some(name => name.startsWith("worker-") && name.endsWith(".log")));
});
