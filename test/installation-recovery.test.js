import {test} from "node:test";
import assert from "node:assert/strict";
import fs from "node:fs/promises";
import os from "node:os";
import path from "node:path";
import {Store} from "../server/store.js";
import {Auth} from "../server/auth.js";
test("a stopped installation copy recovers accounts, history, trash, projects and new edits",async t=>{
  const root=await fs.mkdtemp(path.join(os.tmpdir(),"pencils-installation-drill-"));
  t.after(()=>fs.rm(root,{recursive:true,force:true}));
  const source=new Store(path.join(root,"original"));await source.init();
  const auth=new Auth(source,true);
  await auth.save({username:"owner",password:"fixture-only-password",admin:true,organisations:{}});
  const p=await source.createProject({title:"Restore drill"});
  const original=await source.createTask(p.id,{title:"Before",body:"Original Markdown"});
  const updated=await source.updateTask(p.id,original.id,{revision:original.revision,title:"After"});
  const deleted=await source.createTask(p.id,{title:"Recover from trash"});
  await source.deleteTask(p.id,deleted.id,deleted.revision);
  source.close();
  await fs.cp(source.root,path.join(root,"restored"),{recursive:true,preserveTimestamps:true});
  const restored=new Store(path.join(root,"restored"));await restored.init();t.after(()=>restored.close());
  const login=await new Auth(restored,true).login({username:"owner",password:"fixture-only-password"},"test");
  assert.equal(login.user.admin,true);
  assert.equal((await restored.snapshot(p.id)).tasks[0].body,"Original Markdown");
  assert.equal((await restored.history(original.file))[0].title,"Before");
  await restored.restoreTrash((await restored.trash())[0].key);
  assert.equal((await restored.snapshot(p.id)).tasks.length,2);
  const saved=await restored.updateTask(p.id,original.id,{revision:updated.revision,title:"Verified after recovery"});
  assert.equal(saved.title,"Verified after recovery");
  assert.equal((await source.snapshot(p.id)).tasks[0].title,"After");
});
